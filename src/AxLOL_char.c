AxLOL_FontMap* fontMap_active = &AxLOL_defaultFont;

AxLOL_Status_t AxLOL_setFont(AxLOL_FontMap* fontMap) {
  if (!fontMap)
    return LOL_NULLPTR;

  fontMap_active = fontMap;

  return LOL_SUCCESS;
}

AxLOL_Status_t AxLOL_putChar(AxLOL_FrameBuffer fb, char c, AxLOL_Coord coord, AxLOL_Color color) {
  AxLOL_Status_t status = LOL_SUCCESS;
  AxLOL_Pattern pattern;

  if (!fb.frame)
    return LOL_NULLPTR;

  if (c & 0x80)
    return LOL_BADPARAM;

  pattern = fontMap_active->char_bitmaps[(uint8_t)c];

  status = AxLOL_applyPattern(fb, pattern, coord, color);

  if (status)
    status |= LOL_INNERFAIL;

  return status;
}
