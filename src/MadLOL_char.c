MadLOL_FontMap* fontMap_active = &MadLOL_defaultFont;

MadLOL_Status_t MadLOL_setFont(MadLOL_FontMap* fontMap) {
  if (!fontMap)
    return LOL_NULLPTR;

  fontMap_active = fontMap;

  return LOL_SUCCESS;
}

MadLOL_Status_t MadLOL_putChar(MadLOL_FrameBuffer fb, char c, MadLOL_Coord coord, MadLOL_Color color) {
  MadLOL_Status_t status = LOL_SUCCESS;
  MadLOL_Pattern pattern;

  if (!fb.frame)
    return LOL_NULLPTR;

  if (c & 0x80)
    return LOL_BADCHAR;

  pattern = fontMap_active->char_bitmaps[(uint8_t)c];

  status = MadLOL_applyPattern(fb, pattern, coord, color);

  if (status)
    status |= LOL_INNERFAIL;

  return status;
}
